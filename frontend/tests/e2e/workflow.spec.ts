test('API failure is visible and retry remains available',async({page})=>{
 await page.goto('/');
 await page.route('**/api/plan',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Qloo temporarily unavailable'})}));
 await page.getByRole('button',{name:'Build my day'}).click();
 await expect(page.getByRole('alert').filter({hasText:'Qloo temporarily unavailable'})).toHaveText('Qloo temporarily unavailable');
 await expect(page.getByRole('button',{name:'Build my day'})).toBeEnabled();
});
